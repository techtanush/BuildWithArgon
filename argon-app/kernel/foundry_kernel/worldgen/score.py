"""Scoring, best-version selection and the generated outputs (05-world/09 §Registry, 10 §6–7).
Per building keep the version with the highest (critical_pass, probe_score, visual_score, realism).
Writes web/src/world/buildings/generated/<dept>.ts, generated/index.ts (seed export shape, indexed by department
id), generated/registry.json and runs/<run_id>/scores.json."""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

from ..ids import utc_now
from . import paths

STOP_VISUAL = 0.75
STOP_REALISM = 0.7


@dataclass
class Version:
    """One building at one iteration."""
    dept: str
    iteration: int
    source: str
    report: dict[str, Any]
    critic: dict[str, Any] | None = None
    captured_iteration: int | None = None  # iteration whose captures these scores come from (carried forward)
    extra: dict[str, Any] = field(default_factory=dict)

    @property
    def probe(self) -> float:
        return float(self.report.get("probe_score", 0.0))

    @property
    def critical_pass(self) -> bool:
        return bool(self.report.get("critical_pass", False))

    @property
    def visual(self) -> float | None:
        return None if not self.critic else self.critic.get("visual_score")

    @property
    def realism(self) -> float | None:
        return None if not self.critic else self.critic.get("realism")

    @property
    def failed(self) -> list[str]:
        return [p["id"] for p in self.report.get("probes", []) if not p.get("pass")]

    def key(self) -> tuple[int, float, float, float]:
        return (1 if self.critical_pass else 0, self.probe, self.visual or 0.0, self.realism or 0.0)

    def good(self) -> bool:
        return self.probe >= 1.0 and (self.visual or 0) >= STOP_VISUAL and (self.realism or 0) >= STOP_REALISM

    def row(self) -> dict[str, Any]:
        out: dict[str, Any] = {"probe": self.probe, "visual": self.visual, "realism": self.realism, "failed": self.failed,
                               "critical_pass": self.critical_pass}
        if self.captured_iteration is not None and self.captured_iteration != self.iteration:
            out["captured_iteration"] = self.captured_iteration
        return out


def invalid_report(dept: str, source: str, errors: list[str], tsc: str = "") -> dict[str, Any]:
    """Probe report for a module that never reached the browser (static/tsc failure): every probe fails."""
    why = "; ".join(errors + ([f"tsc: {tsc[:600]}"] if tsc else [])) or "invalid module"
    probes = [{"id": p, "pass": False, "details": (f"module failed validation: {why}" if p == "P1" else "not run (module invalid)")}
              for p in paths.PROBES]
    return {"building": dept, "source": source, "probes": probes, "probe_score": 0.0, "critical_pass": False,
            "screenshots": {}, "videos": {}, "stats": {}, "consoleErrors": [], "invalid": True}


def better(a: Version, b: Version | None) -> bool:
    return b is None or a.key() > b.key()


def mean(values: list[float]) -> float | None:
    return round(sum(values) / len(values), 4) if values else None


def iteration_entry(n: int, versions: dict[str, Version]) -> dict[str, Any]:
    vs = list(versions.values())
    return {"n": n, "world_score": mean([v.probe for v in vs]) or 0.0,
            "visual_score": mean([v.visual for v in vs if v.visual is not None]),
            "realism": mean([v.realism for v in vs if v.realism is not None]),
            "by_building": {v.dept: v.row() for v in vs}}


def registry_entry(best: Version | None, max_iter_reason: str = "") -> dict[str, Any]:
    if best is None:
        return {"status": "fallback", "reason": "no module was generated"}
    if not best.critical_pass:
        failed = [p for p in best.failed if p in paths.CRITICAL_PROBES]
        return {"status": "fallback", "reason": f"{', '.join(failed) or 'critical probes'} failed{max_iter_reason}",
                "iteration": best.iteration, "probe_score": best.probe}
    return {"status": "generated", "iteration": best.iteration, "probe_score": best.probe,
            "visual_score": best.visual, "realism": best.realism}


def write_index(statuses: dict[str, dict[str, Any]]) -> str:
    """generated/index.ts keeping the seed's export shape; only modules with status 'generated' and a file."""
    names = [d for d in paths.department_ids()
             if statuses.get(d, {}).get("status") == "generated" and (paths.GENERATED_DIR / f"{d}.ts").exists()]
    lines = ["// OWNER: generated by ayan's worldgen (worldgen/score.py). Do not hand-edit.",
             "import type { BuildingModule } from '../../kit/types';"]
    lines += [f"import {paths.ident(d)} from './{d}';" for d in names]
    entries = ", ".join(paths.ident(d) if paths.ident(d) == d else f"'{d}': {paths.ident(d)}" for d in names)
    lines.append("")
    lines.append(f"export const generatedModules: Partial<Record<string, BuildingModule>> = {{{(' ' + entries + ' ') if entries else ''}}};")
    text = "\n".join(lines) + "\n"
    (paths.GENERATED_DIR / "index.ts").write_text(text)
    return text


def read_registry() -> dict[str, Any]:
    try:
        return json.loads((paths.GENERATED_DIR / "registry.json").read_text())
    except (OSError, ValueError):
        return {"run_id": None, "generated_at": None, "modules": {}}


def write_registry(registry: dict[str, Any]) -> None:
    paths.GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    (paths.GENERATED_DIR / "registry.json").write_text(json.dumps(registry, indent=2) + "\n")
    write_index(registry.get("modules", {}))


def write_outputs(run_id: str, best: dict[str, Version | None], *, reason_suffix: str = "") -> dict[str, Any]:
    """Final step of a run: generated/<dept>.ts for 'generated' buildings (stale files of fallback buildings are
    removed), registry.json, index.ts. Only the departments in `best` change (a `--only` run keeps the others'
    entries and files)."""
    paths.GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    modules: dict[str, Any] = dict(read_registry().get("modules", {}))
    for dept in paths.department_ids():
        if dept not in best:
            continue
        b = best.get(dept)
        entry = registry_entry(b, reason_suffix)
        target = paths.GENERATED_DIR / f"{dept}.ts"
        if entry["status"] == "generated" and b is not None:
            target.write_text(b.source)
        elif target.exists():
            target.unlink()
        modules[dept] = entry
    registry = {"run_id": run_id, "generated_at": utc_now(), "modules": modules}
    write_registry(registry)
    return registry


def promote_module(dept: str, source: str, entry: dict[str, Any]) -> dict[str, Any]:
    """Live-round promote: replace generated/<dept>.ts and update registry.json + index.ts for one building."""
    paths.GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    (paths.GENERATED_DIR / f"{dept}.ts").write_text(source)
    registry = read_registry()
    registry.setdefault("modules", {})[dept] = {"status": "generated", **entry}
    registry["generated_at"] = utc_now()
    write_registry(registry)
    return registry
