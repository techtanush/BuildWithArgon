"""Deterministic fake LLM for LLM_MODE=fake and tests. Per-job canned outputs live in
kernel/tests/fixtures/fake_llm/<job>.json (a JSON list; strings are returned as-is, objects as JSON).
Each person adds fixtures for the jobs they own (new files only)."""
from __future__ import annotations

import json
from collections.abc import Iterator
from itertools import cycle
from typing import Any

from pydantic import BaseModel

from ..config import KERNEL_DIR
from ..contracts import LLMResult, Part
from .jsonout import parse_model

FIXTURES = KERNEL_DIR / "tests" / "fixtures" / "fake_llm"

DEFAULT = {"title": "Fake output", "summary": "Generated by the fake LLM.",
           "content_md": "## Fake\nThis content was generated in LLM_MODE=fake.", "messages": []}


class FakeLLM:
    def __init__(self) -> None:
        self._scripts: dict[str, Iterator[str]] = {}
        self.calls: list[tuple[str, str]] = []

    def script(self, job: str, outputs: list[Any]) -> None:
        self._scripts[job] = iter([o if isinstance(o, str) else json.dumps(o) for o in outputs])

    def _next(self, job: str) -> str:
        if job in self._scripts:
            try:
                return next(self._scripts[job])
            except StopIteration:
                del self._scripts[job]
        path = FIXTURES / f"{job}.json"
        if path.exists():
            items = json.loads(path.read_text())
            self._scripts[job] = cycle([o if isinstance(o, str) else json.dumps(o) for o in items])
            return next(self._scripts[job])
        return json.dumps(DEFAULT)

    async def generate(self, job: str, prompt: str | list[Part], **kw: Any) -> LLMResult:
        text = self._next(job)
        self.calls.append((job, prompt if isinstance(prompt, str) else "<parts>"))
        return LLMResult(text=text, interaction_id=f"fake-{len(self.calls)}", model=f"fake:{job}",
                         tokens_in=len(str(prompt)) // 4, tokens_out=len(text) // 4)

    async def generate_json(self, job: str, prompt: str | list[Part], schema: type[BaseModel], **kw: Any) -> tuple[BaseModel, LLMResult]:
        res = await self.generate(job, prompt, **kw)
        return parse_model(res.text, schema), res

    async def run_agent(self, *, agent: str, agent_config: dict[str, Any], prompt: str, environment: Any, **kw: Any) -> LLMResult:
        return await self.generate("antigravity", prompt)

    async def generate_images(self, job: str, prompt: str, n: int = 1, reference_images: list[Part] | None = None) -> LLMResult:
        return LLMResult(text="", interaction_id=None, model=f"fake:{job}", images=[])
